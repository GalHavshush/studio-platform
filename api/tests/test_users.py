import uuid

import pytest
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError

from app.models import User


# These tests never commit: rows are flushed (sent to Postgres) and rolled back when the
# session closes, so tests can't leak data into each other.
async def test_insert_and_read_user(db_session):
    db_session.add(User(email="ada@example.com", name="Ada"))
    await db_session.flush()

    user = await db_session.scalar(select(User).where(User.email == "ada@example.com"))

    assert user.name == "Ada"
    assert isinstance(user.id, uuid.UUID)  # generated by Postgres, not by us
    assert user.locale == "en"  # server default


async def test_duplicate_email_is_rejected(db_session):
    db_session.add_all([User(email="a@example.com", name="A"), User(email="a@example.com", name="B")])

    with pytest.raises(IntegrityError):
        await db_session.flush()
