"""Creates the pilot studio with an owner, a coach and a member: `uv run python -m app.seed`.

This is how a studio gets created (no self-serve signup). The data below is placeholder; swap in
a real studio's details when onboarding a pilot. Safe to run repeatedly.
"""

import asyncio

from sqlalchemy import func, select
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession

from app.db import get_engine
from app.models import Membership, Participant, Tenant, User
from app.security import hash_password

PILOT_TENANT = {
    "name": "Pilot Studio",
    "slug": "pilot-studio",
    "timezone": "Asia/Jerusalem",
    "modules": [
        "booking"
    ],  # lets you try steps 23-27 locally; a real pilot lists only what it paid for
}
# Placeholder for local dev. Real pilots get their own passwords (invite flow comes in step 50).
PILOT_PASSWORD = "change-me-pilot"
# (email, name, role). One membership per person at their highest role: roles are cumulative.
PILOT_PEOPLE = [
    ("owner@example.com", "Olivia Owner", "owner"),
    ("coach@example.com", "Cody Coach", "coach"),
    ("member@example.com", "Maya Member", "member"),
]


# ponytail: ON CONFLICT DO NOTHING never updates existing rows, so editing a role above won't
# change a membership that already exists; switch to DO UPDATE if the seed must reconcile.
async def seed(session: AsyncSession) -> None:
    """Create the pilot studio and its people. Safe to run repeatedly; the caller commits."""
    tenant_stmt = insert(Tenant).values(PILOT_TENANT)
    # Modules are re-applied on every run (the seed is the only way to change them for now); the
    # rest of an existing tenant is left alone.
    await session.execute(
        tenant_stmt.on_conflict_do_update(
            index_elements=["slug"], set_={"modules": tenant_stmt.excluded.modules}
        )
    )
    # Hash once: argon2 is deliberately slow, and each hash gets its own salt anyway.
    password_hash = hash_password(PILOT_PASSWORD)
    stmt = insert(User).values(
        [
            {"email": email, "name": name, "password_hash": password_hash}
            for email, name, _ in PILOT_PEOPLE
        ]
    )
    # Fill in a missing hash (users seeded before step 9) but never overwrite an existing one.
    await session.execute(
        stmt.on_conflict_do_update(
            index_elements=["email"],
            set_={"password_hash": func.coalesce(User.password_hash, stmt.excluded.password_hash)},
        )
    )

    # Ids are generated by Postgres, so read them back instead of assuming them.
    tenant_id = await session.scalar(select(Tenant.id).where(Tenant.slug == PILOT_TENANT["slug"]))
    rows = await session.execute(
        select(User.email, User.id).where(User.email.in_([email for email, _, _ in PILOT_PEOPLE]))
    )
    user_ids = {email: user_id for email, user_id in rows}

    await session.execute(
        insert(Membership)
        .values(
            [
                {"tenant_id": tenant_id, "user_id": user_ids[email], "role": role}
                for email, _, role in PILOT_PEOPLE
            ]
        )
        .on_conflict_do_nothing(index_elements=["tenant_id", "user_id"])
    )
    # Everyone with a membership is also a participant of that studio.
    await session.execute(
        insert(Participant)
        .from_select(
            ["tenant_id", "user_id", "name"],
            select(Membership.tenant_id, Membership.user_id, User.name)
            .join(User, User.id == Membership.user_id)
            .where(Membership.tenant_id == tenant_id),
        )
        .on_conflict_do_nothing(index_elements=["tenant_id", "user_id"])
    )


async def main() -> None:
    # session.begin() commits when the block ends and rolls back if anything raises.
    async with AsyncSession(get_engine()) as session, session.begin():
        await seed(session)
    await get_engine().dispose()
    print(f"Seeded {PILOT_TENANT['slug']} (safe to run again).")


if __name__ == "__main__":
    asyncio.run(main())
