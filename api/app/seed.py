"""Creates the pilot studio with an owner, a coach and a member: `uv run python -m app.seed`.

This is how a studio gets created (no self-serve signup). The data below is placeholder; swap in
a real studio's details when onboarding a pilot. Safe to run repeatedly.
"""

import asyncio

from sqlalchemy import select
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession

from app.db import get_engine
from app.models import Membership, Tenant, User

PILOT_TENANT = {"name": "Pilot Studio", "slug": "pilot-studio", "timezone": "Asia/Jerusalem"}
# (email, name, role). One membership per person at their highest role: roles are cumulative.
PILOT_PEOPLE = [
    ("owner@example.com", "Olivia Owner", "owner"),
    ("coach@example.com", "Cody Coach", "coach"),
    ("member@example.com", "Maya Member", "member"),
]


# ponytail: ON CONFLICT DO NOTHING never updates existing rows, so editing a role above won't
# change a membership that already exists; switch to DO UPDATE if the seed must reconcile.
async def seed(session: AsyncSession) -> None:
    """Create the pilot studio and its people. Safe to run repeatedly; the caller commits."""
    await session.execute(
        insert(Tenant).values(PILOT_TENANT).on_conflict_do_nothing(index_elements=["slug"])
    )
    await session.execute(
        insert(User)
        .values([{"email": email, "name": name} for email, name, _ in PILOT_PEOPLE])
        .on_conflict_do_nothing(index_elements=["email"])
    )

    # Ids are generated by Postgres, so read them back instead of assuming them.
    tenant_id = await session.scalar(select(Tenant.id).where(Tenant.slug == PILOT_TENANT["slug"]))
    rows = await session.execute(
        select(User.email, User.id).where(User.email.in_([email for email, _, _ in PILOT_PEOPLE]))
    )
    user_ids = {email: user_id for email, user_id in rows}

    await session.execute(
        insert(Membership)
        .values(
            [
                {"tenant_id": tenant_id, "user_id": user_ids[email], "role": role}
                for email, _, role in PILOT_PEOPLE
            ]
        )
        .on_conflict_do_nothing(index_elements=["tenant_id", "user_id"])
    )


async def main() -> None:
    # session.begin() commits when the block ends and rolls back if anything raises.
    async with AsyncSession(get_engine()) as session, session.begin():
        await seed(session)
    await get_engine().dispose()
    print(f"Seeded {PILOT_TENANT['slug']} (safe to run again).")


if __name__ == "__main__":
    asyncio.run(main())
